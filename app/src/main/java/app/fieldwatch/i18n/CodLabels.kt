fun CodDecoder.Decoded.displaySummary(): String = buildString {
    append(codLabel(major))
    if (minor.isNotBlank() && minor != "Uncategorized") append(" / ").append(codLabel(minor))
    if (services.isNotEmpty()) append(" · ").append(services.joinToString(", ") { codLabel(it) })
}

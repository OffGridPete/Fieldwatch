// Rebuild explicit Android resource references after adding domain/catalog text.
// Usage: node tools/update-i18n-resources.mjs [--check]
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.join(root, 'app/src/main/java/app/fieldwatch');
const target = path.join(source, 'i18n/TextResources.kt');
const xml = fs.readFileSync(path.join(root, 'app/src/main/res/values/strings.xml'), 'utf8');
const available = new Set([...xml.matchAll(/<string\s+name="([a-z0-9_]+)"/g)].map(x => x[1]));
function files(dir) {
    return fs.readdirSync(dir, {withFileTypes: true}).flatMap(entry => {
        const file = path.join(dir, entry.name);
        return entry.isDirectory() ? files(file) : entry.name.endsWith('.kt') ? [file] : [];
    });
}
const required = new Set([...available].filter(key => /^(catalog_|preset_|decode_boolean_)/.test(key)));
for (const file of files(source).filter(file => file !== target)) {
    for (const match of fs.readFileSync(file, 'utf8').matchAll(/localized\("([a-z0-9_]+)"/g)) required.add(match[1]);
}
const missing = [...required].filter(key => !available.has(key));
if (missing.length) throw new Error(`Missing default strings: ${missing.join(', ')}`);
const keys = [...required].sort();
const groups = Array.from({length: Math.ceil(keys.length / 100)}, (_, i) => keys.slice(i * 100, (i + 1) * 100));
const output = 'package app.fieldwatch.i18n\n\nimport app.fieldwatch.R\n\n' +
    '// Generated by tools/update-i18n-resources.mjs. Explicit references survive resource shrinking.\n' +
    'internal object TextResources {\n    val ids: Map<String, Int> = ' + groups.map((_, i) => `group${i}()`).join(' + ') + '\n' +
    groups.map((group, i) => `\n    private fun group${i}(): Map<String, Int> = mapOf(\n` +
        group.map(key => `        "${key}" to R.string.${key},`).join('\n') + '\n    )\n').join('') + '}\n';
if (process.argv.includes('--check')) {
    if (fs.readFileSync(target, 'utf8').replaceAll('\r\n', '\n') !== output) throw new Error('TextResources.kt is stale. Run this tool without --check.');
} else fs.writeFileSync(target, output);
console.log(`${keys.length} domain/catalog resources ${process.argv.includes('--check') ? 'verified' : 'registered'}.`);
